package dev.wildware.udea.build

import java.io.File
import java.security.MessageDigest

/**
 * Makes "frozen means frozen" a checkable claim about `docs/contracts/`.
 *
 * `AGENTS.md` states the rule in the imperative — *"`docs/contracts/` holds the frozen
 * contracts. Frozen means frozen: if your work needs one to change, stop and say so. Do not
 * change it and carry on."* — and until issue #174 nothing in the repository enforced it. The
 * only thing between a frozen contract and a silent edit was a reviewer noticing it in a diff.
 *
 * Every other cross-cutting agreement here outgrew that, and this is the same pattern: the wire
 * ids have `net-protocol.lock` and `udeaCheckProtocolLock`, the generated bytes have
 * `expected-generated-hashes.txt`, the module arrows have `udeaVerifyModuleGraph`, and
 * `AGENTS.md` itself has `udeaVerifyAgentsMd`. `docs/contracts.lock` is the digest, and
 * [VERIFY_TASK] on `check` is what reads it.
 *
 * ## Why this is worth a gate at all
 *
 * What is in that directory is not a description of code that would fail without it. These are
 * the agreements several modules *independently* implement, which is why the spec freezes them
 * in Phase 0. The one `AGENTS.md` singles out — `fieldNames[i]` == `FieldMask` bit *i* ==
 * `FieldStore` field index *i* — is singled out precisely because breaking it does not fail, it
 * lies. An enforcement anchored to a document that can move is not anchored.
 *
 * ## What is compared
 *
 * A set, not a list of the filenames that happen to be there today. Digests keyed by known name
 * would notice an *edit* and miss every way a contract can change without one being edited: a
 * file appearing that nobody agreed to freeze, one vanishing, and a rename — which is both at
 * once. [findings] reports each of those, from a comparison of the whole directory against the
 * whole lock.
 */
public object ContractFreeze {

    /** A file in `docs/contracts/` no longer matches the digest the lock froze it at. */
    public val CONTRACT_CHANGED: RuleId = RuleId("UDEA-FRZ-001")

    /** A file is in `docs/contracts/` that the lock does not freeze. */
    public val CONTRACT_ADDED: RuleId = RuleId("UDEA-FRZ-002")

    /** The lock freezes a file that is no longer in `docs/contracts/`. */
    public val CONTRACT_REMOVED: RuleId = RuleId("UDEA-FRZ-003")

    /** The frozen directory, repo-relative. */
    public const val DIRECTORY: String = "docs/contracts"

    /**
     * The lock, repo-relative — deliberately **beside** the frozen directory rather than in it.
     *
     * A lock inside `docs/contracts/` would have to exclude itself from its own digest, and an
     * excluded name inside the guarded directory is a hole in the guard: anything committed
     * under that name is unfrozen by construction. Outside, the gate covers 100% of the
     * directory with no exception to remember.
     */
    public const val LOCK_PATH: String = "docs/contracts.lock"

    /** The gate that reads the lock. On `check`, so a fresh clone catches an edit. */
    public const val VERIFY_TASK: String = "udeaVerifyContracts"

    /** The one sanctioned way to move the lock, named in every message this object writes. */
    public const val WRITE_TASK: String = "udeaWriteContractLock"

    /**
     * A lock row: a repo-relative path, two spaces, a hex digest.
     *
     * The `{64}` is SHA-256's hex length rather than a magic number, and matching it exactly is
     * what makes a truncated or hand-typed digest a parse failure instead of a row that freezes
     * nothing.
     */
    private val ROW = Regex("""^(\S+)\s\s+([0-9a-f]{64})$""")

    /**
     * SHA-256 of [text] with its line endings normalised to `\n`, as lowercase hex.
     *
     * Normalised rather than raw bytes because of what issue #176 cost the last gate that
     * skipped this step. This repository has no root `.gitattributes` and Git for Windows
     * checks out with `core.autocrlf=true`, so these documents arrive CRLF there. A digest of
     * the raw bytes would be red on a **perfect** tree on Windows, and a gate that cannot tell
     * its own subject apart is a gate somebody switches off. Normalising costs nothing in
     * strictness: every content byte still reaches the digest.
     *
     * Deliberately **not** [MigrationLedger.contentHash], which is the other SHA-256 in this
     * package: that one hashes `normalise`d lines — trimmed, trivia dropped — because it exists
     * to recognise a *copied* source file through reformatting. A frozen contract has to be
     * byte-faithful, so a hash that can miss an edit is the wrong tool, however similar the four
     * lines look.
     */
    public fun digest(text: String): String {
        val normalised = text.replace("\r\n", "\n").replace("\r", "\n")
        return MessageDigest.getInstance("SHA-256")
            .digest(normalised.toByteArray(Charsets.UTF_8))
            .joinToString("") { "%02x".format(it) }
    }

    /**
     * Every file under [directory], keyed repo-relative to [repoRoot] with forward slashes.
     *
     * Walked recursively, so a contract filed under a new subdirectory is frozen too rather
     * than being outside the gate by virtue of where it was put.
     *
     * Repo-relative and forward-slashed, always: spec section 5 makes that a contract for
     * `SourceSpan`, and a lock file that differs by checkout location or by platform is a lock
     * file that fails for everyone but its author.
     */
    public fun digestsOf(directory: File, repoRoot: File): Map<String, String> =
        directory.walkTopDown()
            .filter { it.isFile }
            .associate { file ->
                val path = file.absoluteFile
                    .toRelativeString(repoRoot.absoluteFile)
                    .replace('\\', '/')
                path to digest(file.readText())
            }
            .toSortedMap()

    /**
     * The digests [lock] froze, keyed by repo-relative path.
     *
     * @throws IllegalArgumentException on a line that is neither blank, a comment, nor a row.
     *   A lock file with an unreadable line is a lock file whose coverage nobody can state, and
     *   skipping the line would silently unfreeze whatever it named.
     */
    public fun parse(lock: String): Map<String, String> =
        lock.lineSequence()
            .map(String::trim)
            .filter { it.isNotEmpty() && !it.startsWith("#") }
            .map { line ->
                val row = requireNotNull(ROW.matchEntire(line)) {
                    "$LOCK_PATH has a line that is not '<path>  <sha-256>': '$line'. " +
                        "Regenerate it with `gradlew $WRITE_TASK` rather than editing it."
                }
                row.groupValues[1] to row.groupValues[2]
            }
            .toMap()

    /** [digests] as the text of the lock file, sorted, with the header that explains itself. */
    public fun render(digests: Map<String, String>): String = buildString {
        appendLine("# SHA-256 of every file in $DIRECTORY/, with line endings normalised to LF.")
        appendLine("#")
        appendLine("# $DIRECTORY/ holds the frozen contracts. Frozen means frozen: if your work needs")
        appendLine("# one to change, stop and say so. Do not change it and carry on.")
        appendLine("#")
        appendLine("# When a change is agreed, that is what this file is for. Run:")
        appendLine("#     gradlew $WRITE_TASK")
        appendLine("# and commit the result in the same change as the contract edit. Review the diff:")
        appendLine("# it is the contract.")
        digests.toSortedMap().forEach { (path, hash) -> append(path).append("  ").append(hash).appendLine() }
    }

    /**
     * Every way [actual] disagrees with [locked], in path order.
     *
     * Sorted so two runs over the same disagreement print the same thing, which is what lets a
     * failure be pasted into an issue and compared against the next run's.
     */
    public fun findings(locked: Map<String, String>, actual: Map<String, String>): List<MigrationFinding> {
        val changed = actual.filter { (path, hash) -> locked[path] != null && locked[path] != hash }
            .map { (path, _) ->
                finding(
                    CONTRACT_CHANGED,
                    path,
                    "this frozen contract no longer matches the digest in $LOCK_PATH, so its " +
                        "content has changed since it was frozen.",
                )
            }
        val added = (actual.keys - locked.keys).map {
            finding(
                CONTRACT_ADDED,
                it,
                "$LOCK_PATH does not freeze this file, so it is in $DIRECTORY/ without having " +
                    "been agreed. A contract nobody froze is not frozen.",
            )
        }
        val removed = (locked.keys - actual.keys).map {
            finding(
                CONTRACT_REMOVED,
                it,
                "$LOCK_PATH freezes this file and it is not in the tree. Several modules " +
                    "independently implement what it says; deleting it does not fail, it lies.",
            )
        }
        return (changed + added + removed).sortedWith(compareBy({ it.path }, { it.rule.value }))
    }

    /**
     * The failure message for [findings], or null when there are none.
     *
     * It repeats `AGENTS.md`'s imperative and then names the deliberate route out, in that
     * order. Both halves are load-bearing: a message that only says "stop" leaves a developer
     * with an agreed change and no way to land it, and that developer deletes the gate.
     */
    public fun report(findings: List<MigrationFinding>): String? =
        findings.takeIf { it.isNotEmpty() }?.let {
            buildString {
                appendLine("$VERIFY_TASK found ${it.size} change(s) to the frozen contracts:")
                appendLine()
                it.forEach { finding -> appendLine("  $finding") }
                appendLine()
                appendLine("$DIRECTORY/ holds the frozen contracts. Frozen means frozen: if your work")
                appendLine("needs one to change, stop and say so. Do not change it and carry on.")
                appendLine()
                appendLine("If the change is agreed, the deliberate route is:")
                appendLine("    gradlew $WRITE_TASK")
                append("then commit $LOCK_PATH in the same change. Review the diff: it is the contract.")
            }
        }

    private fun finding(rule: RuleId, path: String, message: String): MigrationFinding =
        MigrationFinding(rule = rule, path = path, line = 1, message = message)
}

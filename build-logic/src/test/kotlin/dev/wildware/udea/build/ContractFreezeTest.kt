package dev.wildware.udea.build

import org.junit.jupiter.api.Test
import java.io.File
import kotlin.test.assertEquals
import kotlin.test.assertFailsWith
import kotlin.test.assertNull
import kotlin.test.assertTrue

/**
 * `docs/contracts/` is frozen, and `docs/contracts.lock` is what makes that a checkable claim.
 *
 * `AGENTS.md` states the rule in the imperative — "Frozen means frozen: if your work needs one
 * to change, stop and say so. Do not change it and carry on" — and until issue #174 the only
 * thing standing behind it was a reviewer noticing an edit in a diff. Every other cross-cutting
 * agreement in this repository outgrew that: the wire ids have `net-protocol.lock`, the
 * generated bytes have `expected-generated-hashes.txt`, the module arrows have
 * `udeaVerifyModuleGraph`, `AGENTS.md` itself has `udeaVerifyAgentsMd`.
 *
 * Some of these read the **real** `docs/contracts/` and the **real** `docs/contracts.lock`, so
 * the files committed alongside this test are the thing being asserted, not a fixture that
 * resembles them. The rest mutate a copy in memory, which is the half that proves the gate can
 * fail — and this gate more than most, because a freeze gate that cannot fail is a freeze that
 * is not happening.
 */
class ContractFreezeTest {

    private val repoRoot: File = generateSequence(File(".").absoluteFile) { it.parentFile }
        .first { File(it, "settings.gradle.kts").isFile && File(it, "AGENTS.md").isFile }

    private val contractsDirectory = File(repoRoot, ContractFreeze.DIRECTORY)
    private val lockFile = File(repoRoot, ContractFreeze.LOCK_PATH)

    /** The committed contracts, keyed the way the lock keys them: repo-relative, forward slashes. */
    private val actual: Map<String, String> = ContractFreeze.digestsOf(contractsDirectory, repoRoot)

    private val locked: Map<String, String> get() = ContractFreeze.parse(lockFile.readText())

    @Test
    fun `the committed lock matches the committed contracts`() {
        assertEquals(emptyList(), ContractFreeze.findings(locked, actual))
    }

    @Test
    fun `the lock freezes every contract in the directory, by name`() {
        assertEquals(
            setOf(
                "docs/contracts/agent-tools.md",
                "docs/contracts/asset-index.md",
                "docs/contracts/replicator.md",
            ),
            actual.keys,
        )
        assertEquals(actual.keys, locked.keys)
    }

    @Test
    fun `the digest is SHA-256 of the newline-normalised text`() {
        // Pinned against the published vector rather than against itself: a "digest" that is
        // really `hashCode()` would satisfy every other test in this class.
        assertEquals("e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855", ContractFreeze.digest(""))
        assertEquals(
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad",
            ContractFreeze.digest("abc"),
        )
    }

    @Test
    fun `editing one byte of a frozen contract is caught, naming the file`() {
        val edited = actual.toMutableMap()
        val contract = "docs/contracts/replicator.md"
        edited[contract] = ContractFreeze.digest(File(repoRoot, contract).readText() + " ")

        val finding = ContractFreeze.findings(locked, edited).single()

        assertEquals(ContractFreeze.CONTRACT_CHANGED, finding.rule)
        assertEquals(contract, finding.path)
    }

    @Test
    fun `a contract added to the directory is caught`() {
        val added = actual + ("docs/contracts/relevancy.md" to ContractFreeze.digest("a fourth contract"))

        val finding = ContractFreeze.findings(locked, added).single()

        assertEquals(ContractFreeze.CONTRACT_ADDED, finding.rule)
        assertEquals("docs/contracts/relevancy.md", finding.path)
    }

    @Test
    fun `a contract deleted from the directory is caught`() {
        val deleted = actual - "docs/contracts/asset-index.md"

        val finding = ContractFreeze.findings(locked, deleted).single()

        assertEquals(ContractFreeze.CONTRACT_REMOVED, finding.rule)
        assertEquals("docs/contracts/asset-index.md", finding.path)
    }

    /**
     * A rename is the case a digest of three known filenames would miss entirely.
     *
     * Neither file's *content* changed, so a gate that only compared the digests it recognised
     * would see nothing. Set membership is what catches it, and it has to be caught from both
     * ends: the old name is gone and the new one was never agreed.
     */
    @Test
    fun `a rename is caught from both ends`() {
        val renamed = (actual - "docs/contracts/replicator.md") +
            ("docs/contracts/replication.md" to actual.getValue("docs/contracts/replicator.md"))

        val findings = ContractFreeze.findings(locked, renamed)

        assertEquals(
            listOf(ContractFreeze.CONTRACT_ADDED to "docs/contracts/replication.md"),
            findings.filter { it.rule == ContractFreeze.CONTRACT_ADDED }.map { it.rule to it.path },
        )
        assertEquals(
            listOf(ContractFreeze.CONTRACT_REMOVED to "docs/contracts/replicator.md"),
            findings.filter { it.rule == ContractFreeze.CONTRACT_REMOVED }.map { it.rule to it.path },
        )
    }

    /**
     * An empty lock is a specific state, not a neutral one.
     *
     * A gate that iterated the lock and checked each row would pass an empty lock against a
     * directory full of contracts — green, and freezing nothing. Deleting `docs/contracts.lock`
     * has to be as loud as editing a contract, because it is the same act with an extra step.
     */
    /**
     * The directory itself removed, which is the deletion case at its largest.
     *
     * Worth its own test because it is the one shape that could break the *plumbing* rather than
     * the rule: an `@InputDirectory` pointing at a missing directory fails Gradle's own
     * validation before a task can say anything, which is why the gate declares a `fileTree`
     * instead.
     */
    @Test
    fun `the whole frozen directory going missing is every contract removed`() {
        val gone = ContractFreeze.digestsOf(File(repoRoot, "docs/contracts-that-are-not-there"), repoRoot)

        assertEquals(emptyMap(), gone)
        assertEquals(
            locked.keys.sorted(),
            ContractFreeze.findings(locked, gone).map { it.path },
        )
        assertTrue(
            ContractFreeze.findings(locked, gone).all { it.rule == ContractFreeze.CONTRACT_REMOVED },
        )
    }

    @Test
    fun `an empty lock freezes nothing and says so, rather than passing`() {
        val findings = ContractFreeze.findings(emptyMap(), actual)

        assertEquals(actual.size, findings.size)
        assertTrue(findings.all { it.rule == ContractFreeze.CONTRACT_ADDED }, findings.toString())
    }

    @Test
    fun `the failure message says stop, and names the deliberate route out`() {
        val message = ContractFreeze.report(ContractFreeze.findings(emptyMap(), actual))!!

        assertTrue("Frozen means frozen" in message, message)
        assertTrue("Do not change it and carry on" in message, message)
        assertTrue(ContractFreeze.WRITE_TASK in message, message)
        assertTrue(ContractFreeze.LOCK_PATH in message, message)
    }

    @Test
    fun `a clean tree produces no message at all`() {
        assertNull(ContractFreeze.report(ContractFreeze.findings(locked, actual)))
    }

    /**
     * The rule and its enforcement stated in the same place, asserted rather than described.
     *
     * `AGENTS.md` is the only document a cold agent reads, and it already carries the
     * imperative. A gate it does not name is a gate the reader has to discover by breaking the
     * build, and the route out is worse to discover that way. Pinned against the constants the
     * convention plugin registers the tasks by, so renaming a task cannot leave the brief
     * describing a command that no longer exists.
     */
    @Test
    fun `AGENTS_md names the gate and the deliberate route out`() {
        val brief = File(repoRoot, "AGENTS.md").readText()

        assertTrue(ContractFreeze.VERIFY_TASK in brief, "AGENTS.md does not name the gate")
        assertTrue(ContractFreeze.WRITE_TASK in brief, "AGENTS.md does not name the route out")
        assertTrue(ContractFreeze.LOCK_PATH in brief, "AGENTS.md does not name the lock file")
    }

    @Test
    fun `the lock round-trips through render and parse`() {
        assertEquals(actual, ContractFreeze.parse(ContractFreeze.render(actual)))
    }

    @Test
    fun `the rendered lock names the write task, so the file explains itself`() {
        val rendered = ContractFreeze.render(actual)

        assertTrue(ContractFreeze.WRITE_TASK in rendered, rendered)
        assertTrue(rendered.lineSequence().first().startsWith("#"), rendered)
    }

    /**
     * Issue #176's lesson, applied before it can cost a CI leg.
     *
     * This repository has no root `.gitattributes` and Git for Windows checks out with
     * `core.autocrlf=true`, so a Windows checkout receives these documents as CRLF. A digest of
     * the raw bytes would be red on a **perfect** tree there, and a gate that is red on its own
     * subject is a gate somebody switches off. The digest is therefore of the normalised text,
     * which is exactly as strict about content and blind only to what the checkout did.
     */
    @Test
    fun `a checkout that translated the line endings does not trip the gate`() {
        val translated = actual.keys.associateWith {
            ContractFreeze.digest(File(repoRoot, it).readText().asCrlf())
        }

        assertEquals(emptyList(), ContractFreeze.findings(locked, translated))
    }

    @Test
    fun `a content change is still caught on a translated checkout`() {
        val contract = "docs/contracts/replicator.md"
        val edited = actual + (
            contract to ContractFreeze.digest(
                File(repoRoot, contract).readText().replace("frozen", "negotiable").asCrlf(),
            )
            )

        assertEquals(
            listOf(ContractFreeze.CONTRACT_CHANGED),
            ContractFreeze.findings(locked, edited).map { it.rule },
        )
    }

    @Test
    fun `a lock line with no digest is a hard failure rather than a silent gap`() {
        assertFailsWith<IllegalArgumentException> {
            ContractFreeze.parse("docs/contracts/replicator.md\n")
        }
    }

    @Test
    fun `comments and blank lines in the lock are ignored`() {
        val hash = actual.getValue("docs/contracts/replicator.md")

        assertEquals(
            mapOf("docs/contracts/replicator.md" to hash),
            ContractFreeze.parse("# a comment\n\ndocs/contracts/replicator.md  $hash\n\n"),
        )
    }

    @Test
    fun `findings are reported in a stable order`() {
        val churned = (actual - "docs/contracts/agent-tools.md") +
            ("docs/contracts/zzz.md" to ContractFreeze.digest("z")) +
            ("docs/contracts/aaa.md" to ContractFreeze.digest("a"))

        assertEquals(
            ContractFreeze.findings(locked, churned).map { it.path }.sorted(),
            ContractFreeze.findings(locked, churned).map { it.path },
        )
    }

    /** The bytes a `core.autocrlf=true` checkout would have written for LF-committed text. */
    private fun String.asCrlf(): String = replace("\r\n", "\n").replace("\n", "\r\n")
}
